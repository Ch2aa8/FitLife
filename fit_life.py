# Проект FitLife - MVP версия 1.0
Value_ml = 30
Value_l = 1000

# 1. Знакомство
# Спроси у пользователя имя и сохрани в переменную user_name
# Спроси возраст и сохрани в
# переменную user_age (не забудь преобразовать в число)
# Вводить имя
user_name = input('Привествую, как тебя зовут? ')
# Вводить лет (int)
user_age = int(input('Сколько тебе лет? '))

# 2. Сбор данных
# Запроси вес (в кг) и сохрани в user_weight (тип float)
# Запроси рост (в метрах, например 1.75) и сохрани в user_height (тип float)
# Вводить вес (float)
user_weight = float(input('Какой у тебя вес? '))
# Вводить рост (float)
user_height = float(input('Какой у тебя рост? (например, 1.75) '))

# 3. Логика расчетов (Функции как "черный ящик": используем арифметику)
# Формула ИМТ: вес разделить на (рост в квадрате)
# Рассчитай bmi (Индекс массы тела)
# Рассчитать индекс массы тела
bmi = round(user_weight / (user_height ** 2), 1)

# Подсчет воды: вес * 30 мл
# Рассчитай water_needed
# Рассчитать норму воды в миллилитрах
water_ml = round(user_weight * Value_ml, 1)
# Перевести в литры
water_l = water_ml / Value_l

# 4. Вывод красивого результата
# Используй f-строку, чтобы вывести приветствие, например: "Привет, Иван!"
# Выведи возраст, ИМТ (округленный до 1 знака) и норму воды.
print('Отчет для пользователя:', user_name.title(), user_age, 'г.')
print(f'Твой Индекс Массы Тела: {bmi}')
print(f'Рекомендуемая норма воды: {water_l} л. в день')
print()
print('Расчет окончен. Будьте здоровы!')
